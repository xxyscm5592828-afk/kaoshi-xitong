let _subjectId = 'math';
function setSubject(id) { _subjectId = id; }

function kp(id, parentId, name, order, level, opts = {}) {
  return {
    id, subjectId: opts.subjectId || _subjectId, parentId, name, order, level,
    grade: opts.grade || '8上',
    bloom: opts.bloom || '应用',
    weight: opts.weight || 3,
    prerequisites: opts.prereq || [],
    tags: opts.tags || [],
  };
}

function q(id, kpId, type, stem, options, answer, explanation, difficulty, expectedTime, opts = {}) {
  return {
    id, subjectId: opts.subjectId || _subjectId, knowledgePointId: kpId, type, stem, options,
    answer, explanation, difficulty, expectedTime,
    groupId: opts.groupId || '', groupRole: opts.role || 'basic',
  };
}

// 正常用时判定表：按（题型 × 难度）取值，由现有题库反向标定（均值圆整到 5 秒）
